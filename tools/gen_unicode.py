"""Generates rust/sqlparse-front/src/pyunicode_tables.rs: the parts of Python 3.11's str (Unicode 14) the port
must reproduce, asked of Python code point by code point.

    python -X utf8 tools/gen_unicode.py

- UPPER, LOWER, TITLE: c.upper(), c.lower(), c.title() where they differ from c (full mappings: 'ß' -> 'SS').
- Final sigma (str.lower turns U+03A3 into U+03C2 at the end of a word): CPython decides it from the Cased and
  Case_Ignorable properties, which Python does not expose; they are read back from lower() itself:
    lower(x + 'Σ') ends in 'ς'      <=>  x is cased and not case-ignorable
    lower('A' + x + 'Σ') ends in 'ς' <=>  x is case-ignorable or cased
  Only these two facts matter to the algorithm (a case-ignorable character is always skipped), so
  CASE_IGNORABLE and CASED (for the others) are exact for what lower() does.
- NOT_PRINTABLE: not c.isprintable(), for repr().
- WORD: what `\w` matches in a str pattern (for ``).
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'rust', 'sqlparse-front', 'src', 'pyunicode_tables.rs')
CPS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def ranges(cps):
    out = []
    for c in cps:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return '[' + ', '.join(f'(0x{a:X}, 0x{b:X})' for a, b in out) + ']'


def mapping(name, fn):
    rows = []
    for cp in CPS:
        c = chr(cp)
        m = fn(c)
        if m != c:
            lit = ''.join(f'\\u{{{ord(x):X}}}' for x in m)
            rows.append(f'    (0x{cp:X}, "{lit}"),')
    return f'pub(crate) static {name}: &[(u32, &str)] = &[\n' + '\n'.join(rows) + '\n];\n', len(rows)


def main():
    parts = [f'//! Generated by tools/gen_unicode.py from Python {sys.version.split()[0]}: do not edit.\n\n']
    for name, fn in (('UPPER', str.upper), ('LOWER', str.lower), ('TITLE', str.title)):
        src, n = mapping(name, fn)
        parts.append(f'/// `c.{name.lower()}()` for every character it changes, sorted.\n' + src + '\n')
        print(name, n)
    ign, cased = [], []
    for cp in CPS:
        x = chr(cp)
        p1 = (x + 'Σ').lower().endswith('ς')
        p2 = ('A' + x + 'Σ').lower().endswith('ς')
        if p2 and not p1:
            ign.append(cp)
        elif p1:
            cased.append(cp)
    parts.append('/// Case_Ignorable, as str.lower() sees it.\n'
                 f'pub(crate) static CASE_IGNORABLE: &[(u32, u32)] = &{ranges(ign)};\n\n')
    parts.append('/// Cased (for characters that are not case-ignorable), as str.lower() sees it.\n'
                 f'pub(crate) static CASED: &[(u32, u32)] = &{ranges(cased)};\n\n')
    nonprint = [cp for cp in CPS if not chr(cp).isprintable()]
    parts.append('/// Not str.isprintable().\n'
                 f'pub(crate) static NOT_PRINTABLE: &[(u32, u32)] = &{ranges(nonprint)};\n')
    word = [cp for cp in CPS if re.match(r'\w', chr(cp))]
    parts.append('\n/// Matched by `\\w` in a str pattern.\n'
                 f'pub(crate) static WORD: &[(u32, u32)] = &{ranges(word)};\n')
    print('case-ignorable', len(ign), 'cased', len(cased), 'not printable', len(nonprint))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(''.join(parts))


if __name__ == '__main__':
    main()
