"""The code points that behave differently, as far as the port can tell, between a Python and CPython 3.11, whose
Unicode 14 tables the Rust is generated from (tools/gen_lexer.py, tools/gen_unicode.py).

    python tools/unicode_drift.py dump OUT.json            # this Python's view of every non-ASCII code point
    python tools/unicode_drift.py diff A.json B.json       # where two views differ
    python tools/unicode_drift.py module REF.json X.json.. # write python/sqlparse_turbo/_unicode_drift.py

The view holds everything the port takes from Python: `re` classes under IGNORECASE | UNICODE (\\w, \\s, \\d,
and which ASCII letters a code point matches case-insensitively, as the lexer's keyword rules do),
str.upper / lower / title / capitalize / isspace / isprintable / strip, the cased and case-ignorable
properties behind lower()'s final sigma, splitlines' breaks, and the general category (so any code point
assigned or reassigned between the versions counts). ASCII is the same in every version.

Run `dump` under each Python (3.11 as the reference), then `module` with the reference first.
"""

import json
import os
import re
import sys
import unicodedata

FLAGS = re.IGNORECASE | re.UNICODE
W = re.compile(r'\w', FLAGS).fullmatch
S = re.compile(r'\s', FLAGS).fullmatch
D = re.compile(r'\d', FLAGS).fullmatch
ASCII_FOLD = {c: re.compile(re.escape(c), FLAGS).fullmatch for c in 'abcdefghijklmnopqrstuvwxyz'}
SIGMA = 'Σ'
FIELDS = ['\\w', '\\s', '\\d', 'ascii fold', 'upper', 'lower', 'capitalize', 'isspace', 'strip', 'splitlines',
          'title', 'isprintable', 'sigma after', 'sigma before', 'category']
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'python', 'sqlparse_turbo', '_unicode_drift.py')


def view(c):
    return [bool(W(c)), bool(S(c)), bool(D(c)), ''.join(a for a, m in ASCII_FOLD.items() if m(c)),
            c.upper(), c.lower(), c.capitalize(), c.isspace(),
            ('x' + c + 'x').strip() != 'x' + c + 'x' or (c + 'x').strip() != c + 'x',
            len(('a' + c + 'b').splitlines()), c.title(), c.isprintable(),
            ('a' + c + SIGMA).lower(), ('a' + SIGMA + c).lower(), unicodedata.category(c)]


def dump(out):
    data = {'python': sys.version.split()[0], 'unicode': unicodedata.unidata_version,
            'cp': {cp: view(chr(cp)) for cp in range(0x80, 0x110000) if not 0xD800 <= cp <= 0xDFFF}}
    with open(out, 'w', encoding='utf-8') as f:
        json.dump(data, f)


def load(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def changed(a, b):
    out = {}
    for cp, va in a['cp'].items():
        vb = b['cp'][cp]
        if va != vb:
            out[int(cp)] = [f for f, x, y in zip(FIELDS, va, vb) if x != y]
    return out


def report(a, b, ch):
    by_field = {}
    for fs in ch.values():
        for f in fs:
            by_field[f] = by_field.get(f, 0) + 1
    print(f"{a['python']} (Unicode {a['unicode']}) vs {b['python']} (Unicode {b['unicode']}): "
          f"{len(ch)} code points differ {by_field}")


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def module(ref_path, others):
    ref = load(ref_path)
    lines = [
        '"""Generated by tools/unicode_drift.py: do not edit.',
        '',
        f"The Rust's Unicode behaviour is CPython {ref['python']}'s (Unicode {ref['unicode']}). For each other Unicode",
        'version a CPython ships, the code points that behave differently there (assigned since, or with other',
        'properties): text holding one of them goes to sqlparse.',
        '"""',
        '',
        f"PORTED_UNICODE = {ref['unicode']!r}",
        '',
        'DRIFT = {',
    ]
    for path in others:
        other = load(path)
        ch = changed(ref, other)
        report(ref, other, ch)
        rs = ranges(ch)
        lines.append(f"    # CPython {other['python']}: {len(ch)} code points in {len(rs)} ranges")
        lines.append(f"    {other['unicode']!r}: (")
        for i in range(0, len(rs), 6):
            lines.append('        ' + ' '.join(f'(0x{a:X}, 0x{b:X}),' for a, b in rs[i:i + 6]))
        lines.append('    ),')
    lines.append('}')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('->', OUT)


if __name__ == '__main__':
    if sys.argv[1] == 'dump':
        dump(sys.argv[2])
    elif sys.argv[1] == 'diff':
        a, b = load(sys.argv[2]), load(sys.argv[3])
        report(a, b, changed(a, b))
    else:
        module(sys.argv[2], sys.argv[3:])
